/** Optional direct-lookup helper (single exact phrase string). */
let _phraseMap: Map<string, PhraseEntry> | null = null;
export function getPhraseMap(): Map<string, PhraseEntry> {
  if (_phraseMap) return _phraseMap;
  const m = new Map<string, PhraseEntry>();
  for (const e of PHRASE_SEED) {
    if (!e.phrase.includes("*")) m.set(e.phrase.toLowerCase(), e);
  }
  _phraseMap = m;
  return m;
}

export function lookupPhrase(s: string): PhraseEntry | undefined {
  return getPhraseMap().get(s.toLowerCase().trim());
}
